"""Post-render citation audit: catch invented or orphaned evidence ids.

Why this exists
---------------
Reports are written in free-form Markdown by the model, while evidence ids are
generated by the retrieval adapter (``register_evidence`` / registry JSON).
Nothing inherently checks the two against each other, so an id that never
existed can appear in the body and look exactly like a real citation.

This module only *reports*. It never edits or deletes body text -- a wrong id is
a signal to review, not something to silently strip.

Three checks
------------
1. **Invented ids**: every ``SRC-xxx`` in the body must exist in this run's
   registry (supports stage-prefixed ``SRC-L1-001`` or channel tags).
2. **Section coverage**: sections that contain zero citations are listed.
   Registry/appendix sections are excluded, because the registry table naturally
   contains every id and would inflate the coverage number.
3. **Weak citations (optional)**: when ``evidence_snippets`` is supplied, each
   citation's surrounding lines are compared against the cited snippet to flag
   "real id cited next to unrelated text". Thresholds are deliberately loose
   and never rewrite anything.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

# SRC-001 / SRC-L1-001 / SRC-WEB-001 / SRC-DOC-001 / SRC-API-001
SRC_RE = re.compile(r"SRC-(?:[A-Z0-9]{1,6}-)?\d{3,4}")
SECTION_RE = re.compile(r"^##\s+(.+)$", re.MULTILINE)
_TERM_RE = re.compile(r"[a-z0-9]{2,}|[\u4e00-\u9fff]{2,}")
_TERM_STOP = frozenset({
    "的", "了", "和", "是", "在", "有", "就", "不", "与", "及", "这", "那", "其",
    "为", "以", "于", "对", "从", "到", "并", "而", "等",
    "我们", "你们", "他们", "可以", "一个", "没有", "已经", "如果", "但是", "因为", "所以",
})

# 区间写法（`[SRC-001 ~ SRC-034]`）是范围标签，不是正文引用。
_RANGE_RE = re.compile(
    r"SRC-(?:[A-Z0-9]{1,6}-)?\d{3,4}\s*[~～]\s*SRC-(?:[A-Z0-9]{1,6}-)?\d{3,4}")


def _mask_ranges(text: str) -> str:
    """把编号区间写法遮掉，只剩真正的引用。"""
    return _RANGE_RE.sub(" ", text or "")


# 注册表本身含全部编号，附录是自动生成的，都不能算"引用覆盖"
DEFAULT_EXCLUDE = ("注册表", "附录", "引用校验", "Evidence Registry")

# 低于这个重合度才提示；阈值刻意放宽，避免把正常概括判成不符
WEAK_OVERLAP = 0.15
MIN_SNIPPET_TERMS = 6


def _terms(text: str) -> list[str]:
    out = []
    for w in _TERM_RE.findall(str(text or "").casefold()):
        if w in _TERM_STOP:
            continue
        if "\u3400" <= w[0] <= "\u9fff" and len(w) > 2:
            out.extend(w[i:i + 2] for i in range(len(w) - 1))
        else:
            out.append(w)
    return out


def _line_no(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def _context_at(text: str, pos: int) -> str:
    """引用所在行 + 前后各一行：概括句常跨行，单行取样会误判。"""
    start = text.rfind("\n", 0, pos) + 1
    prev_start = text.rfind("\n", 0, max(0, start - 1)) + 1
    end = text.find("\n", pos)
    if end == -1:
        end = len(text)
    nxt_end = text.find("\n", end + 1)
    if nxt_end == -1:
        nxt_end = len(text)
    return text[prev_start:nxt_end]


def _weak_citations(body: str, evidence_snippets: dict) -> list[dict]:
    """引用存在、但所在上下文与被引证据几乎无重合 → 疑似"引错内容"。"""
    seen: dict[str, dict] = {}
    for m in SRC_RE.finditer(body):
        sid = m.group(0)
        snippet = evidence_snippets.get(sid)
        if not snippet:
            continue
        ev_terms = set(_terms(snippet))
        if len(ev_terms) < MIN_SNIPPET_TERMS:
            continue
        ctx_terms = set(_terms(_context_at(body, m.start())))
        overlap = len(ev_terms & ctx_terms) / len(ev_terms)
        if overlap < WEAK_OVERLAP:
            prev = seen.get(sid)
            item = {"id": sid, "line": _line_no(body, m.start()),
                    "overlap": round(overlap, 3)}
            if prev is None or item["overlap"] < prev["overlap"]:
                seen[sid] = item
    return sorted(seen.values(), key=lambda x: x["overlap"])


_POLARITY_PAIRS: tuple[tuple[str, str, str], ...] = (
    (
        r"不支持|不再支持|并未支持|没有支持|未支持|不具备|无法支持|不能支持|(?<![a-z])(?:unsupported|does not support|doesn't support|not support)(?![a-z])",
        r"(?<!不)(?<!未)(?<!没)(?<!再)(?<!无)(?<!不再)(?<!没有)(?<!并未)(?<!尚未)(?<!无法)(?<!不能)支持|(?<![a-z])(?<!not )supported(?![a-z])",
        "支持/不支持",
    ),
    (
        r"未修复|没修复|尚未修复|仍未修复|并未修复|没有修复|(?<![a-z])(?:unfixed|not fixed|unresolved)(?![a-z])",
        r"(?<!未)(?<!没)(?<!尚未)(?<!仍未)(?<!并未)(?<!没有)修复|(?<![a-z])(?<!not )(?:fixed|resolved)(?![a-z])",
        "已修复/未修复",
    ),
    (
        r"无法正常(?:使用|运行|工作)|不能正常(?:使用|运行)|无法使用|不能使用|无法运行|无法连接|无法登录|不可用|已失效|彻底失效|(?<![a-z])(?:broken|unavailable|unusable|cannot run|can't run|cannot use|can't use)(?![a-z])",
        r"(?<!不)(?<!没)(?<!未)可用|正常使用|正常运行|正常工作|稳定运行|(?<![a-z])(?<!not )works(?![a-z])",
        "可用/不可用",
    ),
    (
        r"不兼容|并不兼容|无法兼容|(?<![a-z])(?:incompatible|not compatible)(?![a-z])",
        r"(?<!不)(?<!并未)(?<!无法)兼容|(?<![a-z])(?<!not )compatible(?![a-z])",
        "兼容/不兼容",
    ),
    (
        r"已弃用|已废弃|已停更|已跑路|停止维护|不再维护|(?<![a-z])(?:deprecated|archived|unmaintained|abandoned)(?![a-z])",
        r"活跃维护|持续更新|正常维护|还在维护|持续维护|(?<![a-z])actively maintained(?![a-z])",
        "维护/停更",
    ),
    (
        r"不推荐|并不推荐|不建议|慎用|劝退|强烈不推荐|(?<![a-z])not recommended(?![a-z])",
        r"(?<!不)(?<!并不)推荐|强烈推荐|值得买|(?<![a-z])(?<!not )recommended(?![a-z])",
        "推荐/不推荐",
    ),
    (
        r"(?:存在|出现|触发|仍有|发生|造成|引起|引发)内存泄[漏露]|(?<!不)(?<!没)(?<!未)(?<!没有)(?<!并未)发现内存泄[漏露]|内存泄[漏露](?:严重|问题|bug|翻车)|(?<![a-z])(?<!no )memory leak(?![a-z])",
        r"(?:无|没有|不存在|已消除|并未发现|未发现|并未出现|未出现|不出现)内存泄[漏露]|(?<![a-z])no memory leak(?![a-z])",
        "内存泄露有无",
    ),
)
_QUESTION_SENT_RE = re.compile(r"(?:[？?]\s*$|是否|有没有|能不能|可不可以)")


def _sentence_at(text: str, pos: int) -> str:
    """Slice the sentence or bullet line enclosing pos (capped at 260 chars)."""
    start = pos
    while start > 0 and text[start - 1] not in "\n。！；!":
        start -= 1
    end = pos
    n = len(text)
    while end < n and text[end] not in "\n。！；!":
        end += 1
    return text[start:end].strip()[:260]


def _polarity_conflicts(body: str, evidence_snippets: dict) -> list[dict]:
    """Detect zero-token negation polarity flips on high-overlap citations."""
    compiled = [
        (re.compile(neg, re.I), re.compile(pos, re.I), label)
        for neg, pos, label in _POLARITY_PAIRS
    ]
    seen: dict[tuple[str, str], dict] = {}
    for m in SRC_RE.finditer(body):
        sid = m.group(0)
        snippet = evidence_snippets.get(sid)
        if not snippet:
            continue
        ev_terms = set(_terms(snippet))
        if len(ev_terms) < MIN_SNIPPET_TERMS:
            continue
        ctx_terms = set(_terms(_context_at(body, m.start())))
        overlap = len(ev_terms & ctx_terms) / len(ev_terms)
        if overlap < WEAK_OVERLAP:
            continue
        sent = _sentence_at(body, m.start())
        if not sent or _QUESTION_SENT_RE.search(sent):
            continue
        ev_text = str(snippet)
        for neg_re, pos_re, label in compiled:
            ev_neg = bool(neg_re.search(ev_text))
            ev_pos = bool(pos_re.search(ev_text))
            cl_neg = bool(neg_re.search(sent))
            cl_pos = bool(pos_re.search(sent))
            if (ev_neg and ev_pos) or (cl_neg and cl_pos):
                continue
            direction = ""
            if (ev_neg and not ev_pos) and (cl_pos and not cl_neg):
                direction = "证据否定 / 正文肯定"
            elif (ev_pos and not ev_neg) and (cl_neg and not cl_pos):
                direction = "证据肯定 / 正文否定"
            if direction and (sid, label) not in seen:
                seen[(sid, label)] = {
                    "id": sid,
                    "line": _line_no(body, m.start()),
                    "pair": label,
                    "direction": direction,
                    "overlap": round(overlap, 3),
                }
    return list(seen.values())


def audit_citations(
    text: str,
    known_ids,
    *,
    exclude_keywords=DEFAULT_EXCLUDE,
    min_per_section: int = 1,
    evidence_snippets: dict | None = None,
) -> dict:
    """Compare body citations against the registry. Read-only."""
    body = _mask_ranges(text or "")
    known = {str(x) for x in (known_ids or [])}
    cited_all = SRC_RE.findall(body)
    cited_set = set(cited_all)
    unknown = sorted(cited_set - known)

    marks = [(m.start(), m.group(1).strip()) for m in SECTION_RE.finditer(body)]
    sections = []
    for i, (pos, title) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(body)
        chunk = body[pos:end]
        if any(k.lower() in title.lower() for k in exclude_keywords):
            continue
        sections.append({"title": title, "citations": len(SRC_RE.findall(chunk))})

    total = len(sections)
    covered = sum(1 for s in sections if s["citations"] >= min_per_section)
    empty = [s["title"] for s in sections if s["citations"] < min_per_section]
    coverage = round(covered * 100.0 / total, 1) if total else None
    body_citations = sum(s["citations"] for s in sections)
    weak = _weak_citations(body, evidence_snippets) if evidence_snippets else []
    polarity = _polarity_conflicts(body, evidence_snippets) if evidence_snippets else []

    if unknown:
        status = "fail"
    elif weak or polarity:
        status = "warn"
    elif total and body_citations and coverage is not None and coverage < 50.0:
        status = "warn"
    else:
        status = "pass"

    return {
        "status": status,
        "cited_total": len(cited_all),
        "body_citations": body_citations,
        "cited_unique": len(cited_set),
        "registered": len(known),
        "unknown_ids": unknown,
        "weak_citations": weak,
        "polarity_warnings": polarity,
        "sections_total": total,
        "sections_covered": covered,
        "coverage_pct": coverage,
        "sections_without_citation": empty,
    }


def render_markdown(report: dict) -> str:
    """Render the audit as an appendix block (never rewrites body content)."""
    icon = {"pass": "✅", "warn": "⚠️", "fail": "🔴"}.get(report.get("status"), "·")
    cov = report.get("coverage_pct")
    if cov is None:
        cov_icon = "—"
        cov_txt = "—"
    elif not report.get("body_citations"):
        cov_icon = "—"
        cov_txt = "不适用（正文不内嵌编号，编号集中在注册表）"
    else:
        cov_icon = "✅" if cov >= 80 else ("⚠️" if cov >= 50 else "🔴")
        cov_txt = f"{report['sections_covered']}/{report['sections_total']}（{cov}%）"
    unknown = report.get("unknown_ids") or []
    polarity = report.get("polarity_warnings") or []
    lines = [
        "",
        "---",
        "",
        f"## 附录 · 证据引用校验 (Citation Audit) {icon}",
        "",
        "> 自动生成，只核对不改正文。规则：正文出现的 `SRC-xxx` 必须存在于本轮证据注册表；"
        "「注册表 / 附录」章节不参与覆盖率统计；没有正文引用时不评覆盖率（数据档案类报告的常态）。",
        "",
        "| 指标 | 结果 | 判定 |",
        "| :--- | ---: | :---: |",
        f"| 正文引用次数 / 全文去重编号 | {report.get('body_citations', 0)} / {report.get('cited_unique', 0)} | — |",
        f"| 注册表编号数 | {report.get('registered', 0)} | — |",
        f"| 编造或越界编号 | {len(unknown)} | {'🔴 需核' if unknown else '✅'} |",
        f"| 引用上下文与证据重合度过低 | {len(report.get('weak_citations') or [])} | "
        f"{'⚠️ 需核' if report.get('weak_citations') else '✅'} |",
        f"| 疑似极性反转（正反说反） | {len(polarity)} | {'⚠️ 需核' if polarity else '✅'} |",
        f"| 正文章节覆盖率 | {cov_txt} | {cov_icon} |",
    ]
    if unknown:
        lines += ["", f"- 🔴 **以下编号不在本轮注册表，引用前必须核实来源**：{', '.join(f'`{x}`' for x in unknown[:20])}"]
    weak = report.get("weak_citations") or []
    if weak:
        detail = "；".join(f"`{w['id']}` L{w['line']}（重合 {w['overlap']:.0%}）" for w in weak[:5])
        lines += ["", f"- ⚠️ **引用了真编号，但上下文与被引证据几乎不重合（疑似引用与内容不符）**：{detail}"]
    if polarity:
        pdetail = "；".join(f"`{p['id']}` L{p['line']}（{p['pair']}：{p['direction']}）" for p in polarity[:5])
        lines += ["", f"- ⚠️ **引用了高重合真编号，但正反极性与被引证据相反（疑似把原文说反）**：{pdetail}"]
    empty = report.get("sections_without_citation") or []
    if empty and report.get("body_citations"):
        shown = "；".join(empty[:3])
        more = f" 等 {len(empty)} 个" if len(empty) > 3 else ""
        lines += ["", f"- ℹ️ **未引用证据的章节**：{shown}{more}"]
    lines.append("")
    return "\n".join(lines)


def audit_and_render(text: str, known_ids, **kwargs) -> tuple[dict, str]:
    report = audit_citations(text, known_ids, **kwargs)
    return report, render_markdown(report)


def load_registry(path: str) -> tuple[list[str], dict[str, str]]:
    """Load known SRC ids and optional snippets from a registry JSON file."""
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    known_ids: list[str] = []
    snippets: dict[str, str] = {}
    if isinstance(data, list):
        for item in data:
            if isinstance(item, str):
                known_ids.append(item)
            elif isinstance(item, dict):
                sid = item.get("src_id") or item.get("id")
                if sid:
                    known_ids.append(str(sid))
                    snip = item.get("snippet") or item.get("text") or ""
                    if snip:
                        snippets[str(sid)] = str(snip)
        return known_ids, snippets

    if isinstance(data, dict):
        if isinstance(data.get("known_ids"), list):
            known_ids.extend(str(x) for x in data["known_ids"])
        for raw_map in (data.get("snippets"), data.get("evidence_snippets")):
            if isinstance(raw_map, dict):
                for k, v in raw_map.items():
                    snippets[str(k)] = str(v)
                    if str(k) not in known_ids:
                        known_ids.append(str(k))
        for item in (data.get("evidence_items") or data.get("items") or []):
            if isinstance(item, dict):
                sid = item.get("src_id") or item.get("id")
                if sid:
                    sid_s = str(sid)
                    if sid_s not in known_ids:
                        known_ids.append(sid_s)
                    snip = item.get("snippet") or item.get("title") or item.get("text") or ""
                    if snip and sid_s not in snippets:
                        snippets[sid_s] = str(snip)
    return known_ids, snippets


def _ensure_utf8_stdio() -> None:
    for _s in (sys.stdout, sys.stderr):
        if hasattr(_s, "reconfigure"):
            try:
                _s.reconfigure(encoding="utf-8", errors="replace")
            except Exception:
                pass


def main(argv=None) -> int:
    _ensure_utf8_stdio()
    if argv is None and len(sys.argv) == 1:
        sample = (
            "## 1. 结论\n这里引用 [SRC-001] 和 [SRC-099]。\n"
            "## 2. 注册表\n| [SRC-001] | [SRC-002] |\n"
        )
        rep, md = audit_and_render(sample, ["SRC-001", "SRC-002"])
        print(json.dumps(rep, ensure_ascii=False, indent=2))
        print(md)
        return 0 if rep["unknown_ids"] == ["SRC-099"] else 1

    ap = argparse.ArgumentParser(description="核对调研报告中的 SRC 引用编号与证据覆盖率")
    ap.add_argument("report", help="待检查的 Markdown 报告路径")
    ap.add_argument("--registry", required=True, help="本轮证据注册表 JSON（含 known_ids 或 items/evidence_items）")
    ap.add_argument("--strict", action="store_true", help="出现编造或越界编号时返回退出码 1")
    ap.add_argument("--json", action="store_true", help="输出 JSON 格式结果")
    args = ap.parse_args(argv)

    if not os.path.exists(args.report):
        print(f"❌ 报告不存在: {args.report}", file=sys.stderr)
        return 2
    if not os.path.exists(args.registry):
        print(f"❌ 注册表不存在: {args.registry}", file=sys.stderr)
        return 2

    with open(args.report, encoding="utf-8") as f:
        text = f.read()
    known_ids, snippets = load_registry(args.registry)
    rep, md = audit_and_render(
        text, known_ids, evidence_snippets=snippets or None
    )
    if args.json:
        print(json.dumps(rep, ensure_ascii=False, indent=2))
    else:
        print(md)

    if args.strict and rep["status"] == "fail":
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
